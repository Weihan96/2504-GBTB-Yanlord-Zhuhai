save(resolve(dir,'plan-direction-correction-audit.json'),report);
manifest.candidate_representations_sha256=hash(candidatePath);
manifest.project_context.manifest_sha256=hash(resolve(dir,'project-context-manifest.json'));
manifest.views.find(v=>v.view==='plan').svg_sha256=hash(svgPath);
